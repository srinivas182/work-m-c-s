import {
  buildBrandTheme,
  brandCssVariables,
  toCssDeclarations,
  type BrandMode,
} from '../brand/css';
import { generatePalette } from '../brand/palette';
import { DEFAULT_BRAND, STATUS_COLORS } from './defaults';

function statusVars(mode: BrandMode): Record<string, string> {
  const vars: Record<string, string> = {};
  for (const [name, hex] of Object.entries(STATUS_COLORS)) {
    const palette = generatePalette(hex)[mode];
    palette.scale.forEach((v, i) => {
      vars[`--wurk-${name}-${i + 1}`] = v;
    });
    vars[`--wurk-${name}-contrast`] = palette.onSolid;
  }
  return vars;
}

function block(mode: BrandMode): string {
  const theme = buildBrandTheme(DEFAULT_BRAND);
  return toCssDeclarations({ ...brandCssVariables(theme, mode), ...statusVars(mode) }, '    ');
}

/**
 * Renders resources/css/tokens.css. Run `pnpm tokens` after changing the engine or
 * defaults; a test fails if the committed file is out of date.
 */
export function renderTokensCss(): string {
  return `/*
 * GENERATED by \`pnpm tokens\` from resources/js/design-system/tokens — do not edit.
 * Colour scales for the default WURK brand and status colours, light and dark.
 */

@layer base {
  :root,
  [data-theme='light'] {
    color-scheme: light;
${block('light')}
  }

  [data-theme='dark'] {
    color-scheme: dark;
${block('dark')}
  }

  @media (prefers-color-scheme: dark) {
    :root:not([data-theme]) {
      color-scheme: dark;
${block('dark').replace(/^ {4}/gm, '      ')}
    }
  }
}
`;
}
